package frc.robot.luverlib.controller;

/**
 * Classe que define constantes para as direções do D-Pad (direcional) de um
 * controle Xbox.
 * 
 * @author Equipe Luvercontrol - FRC 10298
 * @version 1.0
 */
public class XboxControllerDPad {
    XboxControllerDPad() {

    }

    /** Direção para o norte do D-Pad */
    public static final int NORTH = 0;

    /** Direção para nordeste (northeast) do D-Pad */
    public static final int NORTH_EAST = 45;

    /** Direção para leste (east) do D-Pad */
    public static final int EAST = 90;

    /** Direção para sudeste (southeast) do D-Pad */
    public static final int SOUTH_EAST = 135;

    /** Direção para sul (south) do D-Pad */
    public static final int SOUTH = 180;

    /** Direção para sudoeste (southwest) do D-Pad */
    public static final int SOUTH_WEST = 225;

    /** Direção para oeste (west) do D-Pad */
    public static final int WEST = 270;

    /** Direção para noroeste (northwest) do D-Pad */
    public static final int NORTH_WEST = 315;
}
